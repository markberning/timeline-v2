#!/usr/bin/env node
// Build the French and Indian War off-the-battlefield THEME narratives.
//
// Reads the gated, final markdown for each theme (audits/war-pipeline/fi-<slug>-final.md)
// and emits a single typed data module the dynamic off-the-battlefield/[theme] route
// consumes through the shared <BattleSectionReader>. F&I analog of _build-fi-phases.mjs:
// prose is authored + gated in the .md, never hand-edited in the .ts. Re-run after
// editing any theme's -final.md.
//
// Markdown conventions (same as _build-fi-phases.mjs, plus a figure anchor):
//   # <Section title>                  → narr.title
//   > eyebrow: <kicker>                 → narr.eyebrow (after title) / preceding ## eyebrow
//   ## <Heading>                        → { h, eyebrow } block
//   [label](/href)   (whole line)       → { pill, plabel } block
//   > quote: <text>                     → { p, q:true } pull-quote block
//   [FIGURE: desc | caption | credit]   → DROPPED for now (anchor for the later
//                                          born-verified image pass; prose ships first)
//   <any other non-blank line>          → { p } paragraph
//   --- meanwhile --- + region:/title:/body:  → narr.meanwhile

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const THEMES = ['ohio-company', 'native-alliances', 'albany-plan', 'acadian-expulsion', 'regulars-provincials', 'war-finance', 'treaty-of-paris', 'pontiacs-war']
const PILL_RE = /^\[([^\]]+)\]\((\/[^\s)]+)\)$/
const FIG_RE = /^\[FIGURE:/i

function parse(md) {
  const lines = md.split('\n')
  let title = '', eyebrow = ''
  const blocks = []
  let meanwhile = null
  let i = 0

  for (; i < lines.length; i++) {
    const t = lines[i].trim()
    if (!t) continue
    if (t.startsWith('# ')) { title = t.slice(2).trim(); i++; break }
    throw new Error(`expected "# Title" first, got: ${t}`)
  }
  for (; i < lines.length; i++) {
    const t = lines[i].trim()
    if (!t) continue
    if (t.startsWith('> eyebrow:')) { eyebrow = t.slice('> eyebrow:'.length).trim(); i++ }
    break
  }

  for (; i < lines.length; i++) {
    const t = lines[i].trim()
    if (!t) continue

    if (t === '--- meanwhile ---') {
      const mw = { region: '', title: '', body: '' }
      for (i++; i < lines.length; i++) {
        const l = lines[i].trim()
        if (l.startsWith('region:')) mw.region = l.slice(7).trim()
        else if (l.startsWith('title:')) mw.title = l.slice(6).trim()
        else if (l.startsWith('body:')) mw.body = l.slice(5).trim()
      }
      meanwhile = mw
      break
    }

    if (FIG_RE.test(t)) {
      // [FIGURE: desc | caption | credit | src?] — the 4th field is the resolved,
      // born-verified image path. Emit an image block once it's filled in; until
      // then the anchor is just a planning note (desc = the image-finding brief).
      const inner = t.replace(/^\[FIGURE:/i, '').replace(/\]\s*$/, '')
      const f = inner.split('|').map(s => s.trim())
      const src = f[3] || ''
      if (src) blocks.push({ fig: src, cap: f[1] || '', credit: f[2] || '' })
      continue
    }

    if (t.startsWith('## ')) {
      const h = t.slice(3).trim()
      let ey
      let j = i + 1
      while (j < lines.length && !lines[j].trim()) j++
      if (j < lines.length && lines[j].trim().startsWith('> eyebrow:')) {
        ey = lines[j].trim().slice('> eyebrow:'.length).trim()
        i = j
      }
      blocks.push(ey ? { h, eyebrow: ey } : { h })
      continue
    }

    if (t.startsWith('> quote:')) { blocks.push({ p: t.slice('> quote:'.length).trim(), q: true }); continue }

    const pill = t.match(PILL_RE)
    if (pill) { blocks.push({ pill: pill[2], plabel: pill[1] }); continue }

    blocks.push({ p: t })
  }

  if (!title) throw new Error('no title parsed')
  const narr = { eyebrow, title, blocks }
  if (meanwhile) narr.meanwhile = meanwhile
  return narr
}

const out = {}
const built = []
for (const s of THEMES) {
  const f = join(ROOT, 'audits/war-pipeline', `fi-${s}-final.md`)
  if (!existsSync(f)) continue
  out[s] = parse(readFileSync(f, 'utf8'))
  built.push(`${s} (${out[s].blocks.length} blocks)`)
}

const banner = `// GENERATED by scripts/_build-fi-themes.mjs from audits/war-pipeline/fi-<slug>-final.md.
// Do NOT hand-edit — edit the gated -final.md and re-run the build script.
// The French and Indian War off-the-battlefield theme narratives, consumed by the
// dynamic off-the-battlefield/[theme] route through the shared <BattleSectionReader>.
`
const body = `import type { Narr } from '@/components/mode/battle-reader'\n\nexport const THEME_NARR: Record<string, Narr> = ${JSON.stringify(out, null, 2)}\n`
const dest = join(ROOT, 'src/app/war-french-indian/off-the-battlefield/theme-narratives.ts')
writeFileSync(dest, banner + '\n' + body)
console.log(`wrote ${dest}\n  built: ${built.join(', ') || '(none)'}`)
