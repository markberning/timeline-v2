#!/usr/bin/env node
// Build the French and Indian War phase-chapter narratives.
//
// Reads the gated, final markdown for each phase (audits/war-pipeline/fi-<phase>-final.md)
// and emits a single typed data module the dynamic [phase] route consumes through the
// shared <BattleSectionReader>. This is the F&I analog of scripts/_build-war-themes.mjs:
// the prose is authored + gated in the .md, never hand-edited in the .ts. Re-run after
// editing any phase's -final.md.
//
// Markdown conventions (authored by the pipeline, see audits/war-content-pipeline.md):
//   # <Chapter title>                  → narr.title
//   > eyebrow: <kicker>                 → narr.eyebrow (when right after the title);
//                                         → the preceding ## heading's eyebrow otherwise
//   ## <Heading>                        → { h, eyebrow } block
//   [label](/href)   (whole line)       → { pill, plabel } block (a "Read the full story" button)
//   > quote: <text>                     → { p, q:true } pull-quote block
//   <any other non-blank line>          → { p } paragraph (inline **bold**/*italic*/[x](/y) kept)
//   --- meanwhile --- + region:/title:/body:  → narr.meanwhile

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const PHASES = ['ohio-spark', 'disaster', 'pitts-turn', 'conquest', 'peace-fuse']
const PILL_RE = /^\[([^\]]+)\]\((\/[^\s)]+)\)$/

function parse(md) {
  const lines = md.split('\n')
  let title = '', eyebrow = ''
  const blocks = []
  let meanwhile = null
  let i = 0

  // title + hero eyebrow
  for (; i < lines.length; i++) {
    const t = lines[i].trim()
    if (!t) continue
    if (t.startsWith('# ')) { title = t.slice(2).trim(); i++; break }
    throw new Error(`expected "# Title" first, got: ${t}`)
  }
  for (; i < lines.length; i++) {
    const t = lines[i].trim()
    if (!t) continue
    if (t.startsWith('> eyebrow:')) { eyebrow = t.slice('> eyebrow:'.length).trim(); i++ }
    break
  }

  for (; i < lines.length; i++) {
    const t = lines[i].trim()
    if (!t) continue

    if (t === '--- meanwhile ---') {
      const mw = { region: '', title: '', body: '' }
      for (i++; i < lines.length; i++) {
        const l = lines[i].trim()
        if (l.startsWith('region:')) mw.region = l.slice(7).trim()
        else if (l.startsWith('title:')) mw.title = l.slice(6).trim()
        else if (l.startsWith('body:')) mw.body = l.slice(5).trim()
      }
      meanwhile = mw
      break
    }

    if (t.startsWith('## ')) {
      const h = t.slice(3).trim()
      let ey
      // peek next non-blank line for an eyebrow
      let j = i + 1
      while (j < lines.length && !lines[j].trim()) j++
      if (j < lines.length && lines[j].trim().startsWith('> eyebrow:')) {
        ey = lines[j].trim().slice('> eyebrow:'.length).trim()
        i = j
      }
      blocks.push(ey ? { h, eyebrow: ey } : { h })
      continue
    }

    if (t.startsWith('> quote:')) { blocks.push({ p: t.slice('> quote:'.length).trim(), q: true }); continue }

    const pill = t.match(PILL_RE)
    if (pill) { blocks.push({ pill: pill[2], plabel: pill[1] }); continue }

    blocks.push({ p: t })
  }

  if (!title) throw new Error('no title parsed')
  const narr = { eyebrow, title, blocks }
  if (meanwhile) narr.meanwhile = meanwhile
  return narr
}

const out = {}
const built = []
for (const p of PHASES) {
  const f = join(ROOT, 'audits/war-pipeline', `fi-${p}-final.md`)
  if (!existsSync(f)) continue
  out[p] = parse(readFileSync(f, 'utf8'))
  built.push(`${p} (${out[p].blocks.length} blocks)`)
}

const banner = `// GENERATED by scripts/_build-fi-phases.mjs from audits/war-pipeline/fi-<phase>-final.md.
// Do NOT hand-edit — edit the gated -final.md and re-run the build script.
// The French and Indian War phase-chapter narratives, consumed by the dynamic
// [phase] route through the shared <BattleSectionReader>.
`
const body = `import type { Narr } from '@/components/mode/battle-reader'\n\nexport const PHASE_NARR: Record<string, Narr> = ${JSON.stringify(out, null, 2)}\n`
const dest = join(ROOT, 'src/app/war-french-indian/phase-narratives.ts')
writeFileSync(dest, banner + '\n' + body)
console.log(`wrote ${dest}\n  built: ${built.join(', ') || '(none)'}`)
