#!/usr/bin/env node
// Build the American Revolution phase-chapter narratives (war #3).
//
// Direct analog of scripts/_build-fi-phases.mjs: reads the gated, final markdown for
// each phase (audits/war-pipeline/rev-<phase>-final.md — the phase slugs never collide
// with the theme slugs) and emits a single typed data module the dynamic [phase] route
// consumes through the shared <BattleSectionReader>. Prose is authored + gated in the
// .md, never hand-edited in the .ts. Re-run after editing any phase's -final.md. A
// phase with no -final.md yet is skipped (its route renders the placeholder).
//
// Markdown conventions are identical to _build-fi-phases.mjs:
//   # <Chapter title>                  → narr.title
//   > eyebrow: <kicker>                 → narr.eyebrow / the preceding ## heading's eyebrow
//   ## <Heading>                        → { h, eyebrow } block
//   [label](/href)   (whole line)       → { pill, plabel } block
//   > quote: <text>                     → { p, q:true } pull-quote block
//   <any other non-blank line>          → { p } paragraph
//   --- meanwhile --- + region:/title:/body:  → narr.meanwhile

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const PHASES = ['outbreak', 'the-north', 'two-armies', 'world-war', 'southern-turn', 'the-peace']
const PILL_RE = /^\[([^\]]+)\]\((\/[^\s)]+)\)$/
const FIG_RE = /^\[FIGURE:/i

function parse(md) {
  const lines = md.split('\n')
  let title = '', eyebrow = ''
  const blocks = []
  let meanwhile = null
  let i = 0

  for (; i < lines.length; i++) {
    const t = lines[i].trim()
    if (!t) continue
    if (t.startsWith('# ')) { title = t.slice(2).trim(); i++; break }
    throw new Error(`expected "# Title" first, got: ${t}`)
  }
  for (; i < lines.length; i++) {
    const t = lines[i].trim()
    if (!t) continue
    if (t.startsWith('> eyebrow:')) { eyebrow = t.slice('> eyebrow:'.length).trim(); i++ }
    break
  }

  for (; i < lines.length; i++) {
    const t = lines[i].trim()
    if (!t) continue

    if (t === '--- meanwhile ---') {
      // Unlike the F&I original (meanwhile always last), Revolution spine chapters may
      // place the block mid-chapter — consume only its region:/title:/body: lines and
      // keep parsing the rest of the file.
      const mw = { region: '', title: '', body: '' }
      let j = i + 1
      for (; j < lines.length; j++) {
        const l = lines[j].trim()
        if (!l) continue
        if (l.startsWith('region:')) mw.region = l.slice(7).trim()
        else if (l.startsWith('title:')) mw.title = l.slice(6).trim()
        else if (l.startsWith('body:')) mw.body = l.slice(5).trim()
        else break
      }
      meanwhile = mw
      i = j - 1
      continue
    }

    if (t.startsWith('## ')) {
      const h = t.slice(3).trim()
      let ey
      let j = i + 1
      while (j < lines.length && !lines[j].trim()) j++
      if (j < lines.length && lines[j].trim().startsWith('> eyebrow:')) {
        ey = lines[j].trim().slice('> eyebrow:'.length).trim()
        i = j
      }
      blocks.push(ey ? { h, eyebrow: ey } : { h })
      continue
    }

    if (t.startsWith('> quote:')) { blocks.push({ p: t.slice('> quote:'.length).trim(), q: true }); continue }

    // [FIGURE: desc | caption | credit | src] → { fig, cap, credit } (same convention
    // as _build-rev-themes.mjs; spine chapters carry born-verified figures too).
    if (FIG_RE.test(t)) {
      const inner = t.replace(/^\[FIGURE:/i, '').replace(/\]\s*$/, '')
      const f = inner.split('|').map(s => s.trim())
      const src = f[3] || ''
      if (src) blocks.push({ fig: src, cap: f[1] || '', credit: f[2] || '' })
      continue
    }

    const pill = t.match(PILL_RE)
    if (pill) { blocks.push({ pill: pill[2], plabel: pill[1] }); continue }

    blocks.push({ p: t })
  }

  if (!title) throw new Error('no title parsed')
  const narr = { eyebrow, title, blocks }
  if (meanwhile) narr.meanwhile = meanwhile
  return narr
}

const out = {}
const built = []
for (const p of PHASES) {
  const f = join(ROOT, 'audits/war-pipeline', `rev-${p}-final.md`)
  if (!existsSync(f)) continue
  const md = readFileSync(f, 'utf8')
  // The gated finals carry a FACT LEDGER tail that never ships — cut it before parsing.
  out[p] = parse(md.split(/^## FACT LEDGER\s*$/m)[0])
  built.push(`${p} (${out[p].blocks.length} blocks)`)
}

const banner = `// GENERATED by scripts/_build-rev-phases.mjs from audits/war-pipeline/rev-<phase>-final.md.
// Do NOT hand-edit — edit the gated -final.md and re-run the build script.
// The American Revolution phase-chapter narratives, consumed by the dynamic
// [phase] route through the shared <BattleSectionReader>.
`
const body = `import type { Narr } from '@/components/mode/battle-reader'\n\nexport const PHASE_NARR: Record<string, Narr> = ${JSON.stringify(out, null, 2)}\n`
const dest = join(ROOT, 'src/app/war-revolution/phase-narratives.ts')
writeFileSync(dest, banner + '\n' + body)
console.log(`wrote ${dest}\n  built: ${built.join(', ') || '(none)'}`)
