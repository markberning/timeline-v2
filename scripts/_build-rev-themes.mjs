#!/usr/bin/env node
// Build the American Revolution off-the-battlefield THEME narratives (war #3).
//
// Direct analog of scripts/_build-fi-themes.mjs: reads the gated final markdown for each
// theme (audits/war-pipeline/rev-<slug>-final.md) and emits a single typed data module
// the dynamic off-the-battlefield/[theme] route consumes through the shared
// <BattleSectionReader>. Prose is authored + gated in the .md, never hand-edited in the
// .ts. Re-run after editing any theme's -final.md. A theme with no -final.md yet is
// skipped (its route renders the graceful "on its way" placeholder).
//
// Markdown conventions (identical to _build-fi-themes.mjs):
//   # <Section title>                  → narr.title
//   > eyebrow: <kicker>                 → narr.eyebrow / a section's ## eyebrow
//   ## <Heading>                        → { h, eyebrow } block
//   [label](/href)   (whole line)       → { pill, plabel } block
//   > quote: <text>                     → { p, q:true } pull-quote block
//   [FIGURE: desc | caption | credit | src] → { fig, cap, credit } when the 4th field
//                                          (the born-verified path) is filled; DROPPED
//                                          while empty (the prose ships before the image)
//   <any other non-blank line>          → { p } paragraph
//   --- meanwhile --- + region:/title:/body:  → narr.meanwhile

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
// Route slugs, in config order. Each maps to audits/war-pipeline/rev-<slug>-final.md and
// to the theme's href in src/lib/wars/revolution.ts.
const THEMES = [
  'bill-comes-due', 'stamp-act', 'boston-massacre', 'tea-party', 'idea-of-independence',
  'civil-war-among-themselves', 'army-from-nothing', 'slavery-and-the-revolution',
  'women-of-the-revolution', 'native-nations', 'french-alliance', 'war-at-sea',
  'treaty-of-paris',
]
const PILL_RE = /^\[([^\]]+)\]\((\/[^\s)]+)\)$/
const FIG_RE = /^\[FIGURE:/i

function parse(md) {
  const lines = md.split('\n')
  let title = '', eyebrow = ''
  const blocks = []
  let meanwhile = null
  let i = 0

  for (; i < lines.length; i++) {
    const t = lines[i].trim()
    if (!t) continue
    if (t.startsWith('# ')) { title = t.slice(2).trim(); i++; break }
    throw new Error(`expected "# Title" first, got: ${t}`)
  }
  for (; i < lines.length; i++) {
    const t = lines[i].trim()
    if (!t) continue
    if (t.startsWith('> eyebrow:')) { eyebrow = t.slice('> eyebrow:'.length).trim(); i++ }
    break
  }

  for (; i < lines.length; i++) {
    const t = lines[i].trim()
    if (!t) continue

    if (t === '--- meanwhile ---') {
      const mw = { region: '', title: '', body: '' }
      for (i++; i < lines.length; i++) {
        const l = lines[i].trim()
        if (l.startsWith('region:')) mw.region = l.slice(7).trim()
        else if (l.startsWith('title:')) mw.title = l.slice(6).trim()
        else if (l.startsWith('body:')) mw.body = l.slice(5).trim()
      }
      meanwhile = mw
      break
    }

    // Everything from the FACT LEDGER tail on is internal — stop emitting.
    if (t.startsWith('## FACT LEDGER')) break

    if (FIG_RE.test(t)) {
      const inner = t.replace(/^\[FIGURE:/i, '').replace(/\]\s*$/, '')
      const f = inner.split('|').map(s => s.trim())
      const src = f[3] || ''
      if (src) blocks.push({ fig: src, cap: f[1] || '', credit: f[2] || '' })
      continue
    }

    if (t.startsWith('## ')) {
      const h = t.slice(3).trim()
      let ey
      let j = i + 1
      while (j < lines.length && !lines[j].trim()) j++
      if (j < lines.length && lines[j].trim().startsWith('> eyebrow:')) {
        ey = lines[j].trim().slice('> eyebrow:'.length).trim()
        i = j
      }
      blocks.push(ey ? { h, eyebrow: ey } : { h })
      continue
    }

    if (t.startsWith('> quote:')) { blocks.push({ p: t.slice('> quote:'.length).trim(), q: true }); continue }

    const pill = t.match(PILL_RE)
    if (pill) { blocks.push({ pill: pill[2], plabel: pill[1] }); continue }

    blocks.push({ p: t })
  }

  if (!title) throw new Error('no title parsed')
  const narr = { eyebrow, title, blocks }
  if (meanwhile) narr.meanwhile = meanwhile
  return narr
}

const out = {}
const built = []
for (const s of THEMES) {
  const f = join(ROOT, 'audits/war-pipeline', `rev-${s}-final.md`)
  if (!existsSync(f)) continue
  out[s] = parse(readFileSync(f, 'utf8'))
  built.push(`${s} (${out[s].blocks.length} blocks)`)
}

const banner = `// GENERATED by scripts/_build-rev-themes.mjs from audits/war-pipeline/rev-<slug>-final.md.
// Do NOT hand-edit — edit the gated -final.md and re-run the build script.
// The American Revolution off-the-battlefield theme narratives, consumed by the dynamic
// off-the-battlefield/[theme] route through the shared <BattleSectionReader>.
`
const body = `import type { Narr } from '@/components/mode/battle-reader'\n\nexport const THEME_NARR: Record<string, Narr> = ${JSON.stringify(out, null, 2)}\n`
const dest = join(ROOT, 'src/app/war-revolution/off-the-battlefield/theme-narratives.ts')
writeFileSync(dest, banner + '\n' + body)
console.log(`wrote ${dest}\n  built: ${built.join(', ') || '(none)'}`)
