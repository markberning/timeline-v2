#!/usr/bin/env node
// Build the cross-cutting THREAD narratives (the "Threads" namespace — stories that run
// across time and cut through the war/civ verticals rather than belonging to one of them).
//
// Direct analog of scripts/_build-rev-themes.mjs: reads the gated final markdown for each
// thread chapter (audits/threads-pipeline/<src>-final.md) and emits a typed data module the
// thread's route renders through its own light ThreadReader (NOT the war chrome — a thread
// is not war-owned). Prose is authored + gated in the .md, never hand-edited in the .ts.
// Re-run after editing any chapter's -final.md.
//
// Markdown conventions (identical to the theme build scripts):
//   # <Chapter title>                       → narr.title
//   > eyebrow: <kicker>                      → narr.eyebrow / a section's ## eyebrow
//   ## <Heading>  (+ optional > eyebrow:)    → { h, eyebrow } block
//   [label](/href)   (whole line)            → { pill, plabel } block
//   > quote: <text>                          → { p, q:true } pull-quote block
//   [FIGURE: alt | caption | credit | src]   → { fig, cap, credit } when the 4th field
//                                             (the self-host path) is filled; DROPPED while
//                                             empty (the prose ships before the image)
//   <any other non-blank line>               → { p } paragraph
// Everything from "## FACT LEDGER" down is internal and is not emitted.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

// slug (route + folder) → source markdown stem under audits/threads-pipeline/.
const THREADS = [
  { slug: 'the-parties', src: 'parties' },
]

const PILL_RE = /^\[([^\]]+)\]\((\/[^\s)]+)\)$/
const FIG_RE = /^\[FIGURE:/i

function parse(md) {
  const lines = md.split('\n')
  let title = '', eyebrow = ''
  const blocks = []
  let i = 0

  for (; i < lines.length; i++) {
    const t = lines[i].trim()
    if (!t) continue
    if (t.startsWith('# ')) { title = t.slice(2).trim(); i++; break }
    throw new Error(`expected "# Title" first, got: ${t}`)
  }
  for (; i < lines.length; i++) {
    const t = lines[i].trim()
    if (!t) continue
    if (t.startsWith('> eyebrow:')) { eyebrow = t.slice('> eyebrow:'.length).trim(); i++ }
    break
  }

  for (; i < lines.length; i++) {
    const t = lines[i].trim()
    if (!t) continue
    if (t.startsWith('## FACT LEDGER')) break

    if (FIG_RE.test(t)) {
      const inner = t.replace(/^\[FIGURE:/i, '').replace(/\]\s*$/, '')
      const f = inner.split('|').map(s => s.trim())
      const src = f[3] || ''
      if (src) blocks.push({ fig: src, cap: f[1] || '', credit: f[2] || '' })
      continue
    }

    if (t.startsWith('## ')) {
      const h = t.slice(3).trim()
      let ey
      let j = i + 1
      while (j < lines.length && !lines[j].trim()) j++
      if (j < lines.length && lines[j].trim().startsWith('> eyebrow:')) {
        ey = lines[j].trim().slice('> eyebrow:'.length).trim()
        i = j
      }
      blocks.push(ey ? { h, eyebrow: ey } : { h })
      continue
    }

    if (t.startsWith('> quote:')) { blocks.push({ p: t.slice('> quote:'.length).trim(), q: true }); continue }

    const pill = t.match(PILL_RE)
    if (pill) { blocks.push({ pill: pill[2], plabel: pill[1] }); continue }

    blocks.push({ p: t })
  }

  if (!title) throw new Error('no title parsed')
  return { eyebrow, title, blocks }
}

for (const { slug, src } of THREADS) {
  const f = join(ROOT, 'audits/threads-pipeline', `${src}-final.md`)
  if (!existsSync(f)) { console.log(`skip ${slug} (no ${src}-final.md)`); continue }
  const narr = parse(readFileSync(f, 'utf8'))
  const dir = join(ROOT, 'src/app/threads', slug)
  mkdirSync(dir, { recursive: true })
  const banner = `// GENERATED by scripts/_build-threads.mjs from audits/threads-pipeline/${src}-final.md.
// Do NOT hand-edit — edit the gated -final.md and re-run the build script.
`
  const body = `import type { Narr } from '@/components/mode/battle-reader'\n\nexport const NARR: Narr = ${JSON.stringify(narr, null, 2)}\n`
  writeFileSync(join(dir, 'narrative.ts'), banner + '\n' + body)
  console.log(`wrote src/app/threads/${slug}/narrative.ts (${narr.blocks.length} blocks)`)
}
